import fs from 'node:fs';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const app=JSON.parse(fs.readFileSync('app.json','utf8')).expo;
const mustDeps=['expo-dev-client','expo-location','expo-image-picker','expo-constants','@react-native-async-storage/async-storage','@maplibre/maplibre-react-native','react-native-url-polyfill'];
const checks=[]; const add=(name,ok,detail='')=>checks.push({name,ok,detail});
add('version_match',pkg.version===app.version,`${pkg.version} / ${app.version}`);
add('ios_bundle',app.ios?.bundleIdentifier==='iq.sanad.app',app.ios?.bundleIdentifier||'');
add('android_package',app.android?.package==='iq.sanad.app',app.android?.package||'');
for(const dep of mustDeps) add(`dependency:${dep}`,Boolean(pkg.dependencies?.[dep]),pkg.dependencies?.[dep]||'missing');
const pluginNames=(app.plugins||[]).map(x=>Array.isArray(x)?x[0]:x);
for(const pl of ['expo-router','expo-dev-client','expo-location','expo-image-picker','expo-notifications','@maplibre/maplibre-react-native']) add(`plugin:${pl}`,pluginNames.includes(pl));
add('field_screen',fs.existsSync('app/field.tsx'));
add('field_service',fs.existsSync('src/services/fieldMode.ts'));
add('native_map',fs.existsSync('src/components/SanadMap.native.tsx'));
add('field_migration',fs.existsSync('supabase/migrations/20260828015457_native_field_mode_033.sql'));
add('eas_project_link',Boolean(app.extra?.eas?.projectId),'expected after eas init');
console.log('\nSanad native readiness\n');
for(const c of checks) console.log(`${c.ok?'PASS':'WAIT'}  ${c.name}${c.detail?` — ${c.detail}`:''}`);
const hard=checks.filter(c=>!c.ok&&c.name!=='eas_project_link'); if(hard.length) process.exitCode=1;
